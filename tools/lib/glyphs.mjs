/** 塗りつぶしのセルの文字コード。HUD のパネルや帯はこの 1 文字で出せる */
export const FILL_CHAR_CODE = 0x7f;

/**
 * 文字コード → 7 行の字形。未定義は空白。
 *
 * 小文字（0x61–0x7A）は**大文字の字形へ落とす**。上のテーブルに小文字を
 * 書いていないのはそのためで、テーブルの重複を持たない。
 */
export function glyphFor(charCode) {
  const upper = charCode >= 0x61 && charCode <= 0x7a ? charCode - 0x20 : charCode;
  return GLYPHS[String.fromCharCode(upper)] ?? GLYPHS[' '];
}

/**
 * 字形の点灯画素を走査する。`plot(x, y)` は字形の左上を原点とする整数座標で呼ばれる。
 * 拡大はしない — 呼び出し側が座標を掛ける（ロゴは 5 倍まで拡大して使う）。
 */
export function forEachGlyphPixel(charCode, plot) {
  const rows = glyphFor(charCode);
  for (let y = 0; y < GLYPH_HEIGHT; y++) {
    const row = rows[y];
    for (let x = 0; x < GLYPH_WIDTH; x++) {
      if (row[x] === '#') plot(x, y);
    }
  }
}
